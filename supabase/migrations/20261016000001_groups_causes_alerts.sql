-- Groups, causes (donations through Razorpay), phone and email alerts, and photo sizes.
-- Runs after 20261015000001_alumnity.sql; safe to run again.

-- ---------- Groups ----------

-- A group: open (anyone may join and read) or private (asked to join; only members read).
create table if not exists groups (
  id bigint generated by default as identity primary key,
  name text not null,
  about text not null default '',
  kind text not null check (kind in ('open', 'private')),
  created_by bigint references users(id) on delete set null,
  removed_at bigint,
  created_at bigint not null
);
create index if not exists groups_created on groups(created_at);

create table if not exists group_members (
  group_id bigint not null references groups(id) on delete cascade,
  user_id bigint not null references users(id) on delete cascade,
  role text not null default 'member' check (role in ('owner', 'admin', 'member')),
  status text not null default 'member' check (status in ('member', 'pending')),
  created_at bigint not null,
  primary key (group_id, user_id)
);
create index if not exists group_members_user on group_members(user_id, status);
create index if not exists group_members_group on group_members(group_id, status);

-- A post in a group is for that group alone.
alter table posts add column if not exists group_id bigint references groups(id) on delete cascade;
create index if not exists posts_group_time on posts(group_id, created_at);
alter table posts drop constraint if exists posts_audience_check;
alter table posts add constraint posts_audience_check check (audience in ('everyone', 'batch', 'connections', 'group'));

alter table reports drop constraint if exists reports_subject_kind_check;
alter table reports add constraint reports_subject_kind_check check (subject_kind in ('member', 'post', 'comment', 'message', 'ask', 'group', 'cause'));

-- ---------- Causes and donations ----------

-- A cause anyone may propose; it's shown once the college desk approves it. Money is in
-- paise (₹1 = 100). Every donation goes to the college's Razorpay account; the desk
-- records what it has paid out to each cause.
create table if not exists causes (
  id bigint generated by default as identity primary key,
  author bigint references users(id) on delete set null,
  title text not null,
  story text not null,
  goal bigint not null check (goal > 0),
  cover text,
  status text not null default 'pending' check (status in ('pending', 'live', 'rejected', 'closed')),
  review_note text,
  reviewed_by bigint references users(id) on delete set null,
  ends_at bigint,
  created_at bigint not null,
  reviewed_at bigint,
  closed_at bigint
);
create index if not exists causes_status on causes(status, created_at);

create table if not exists donations (
  id bigint generated by default as identity primary key,
  cause_id bigint not null references causes(id) on delete restrict,
  donor bigint references users(id) on delete set null,
  amount bigint not null check (amount > 0),
  -- Razorpay's order, made by our server; the payment, once Razorpay confirms it.
  order_id text not null unique,
  payment_id text unique,
  status text not null default 'created' check (status in ('created', 'paid', 'failed')),
  anonymous integer not null default 0,
  message text not null default '',
  created_at bigint not null,
  paid_at bigint
);
create index if not exists donations_cause on donations(cause_id, status);
create index if not exists donations_donor on donations(donor, created_at);

create table if not exists cause_payouts (
  id bigint generated by default as identity primary key,
  cause_id bigint not null references causes(id) on delete restrict,
  amount bigint not null check (amount > 0),
  note text not null,
  paid_by bigint references users(id) on delete set null,
  created_at bigint not null
);

-- ---------- Alerts ----------

-- A browser that asked for phone notifications (Web Push).
create table if not exists push_subscriptions (
  endpoint text primary key,
  user_id bigint not null references users(id) on delete cascade,
  p256dh text not null,
  auth text not null,
  created_at bigint not null
);
create index if not exists push_user on push_subscriptions(user_id);

-- Each member's alert choices (no row: the defaults, both on).
create table if not exists member_prefs (
  user_id bigint primary key references users(id) on delete cascade,
  email_digest integer not null default 1,
  push integer not null default 1,
  last_digest_at bigint
);

-- ---------- Photo sizes ----------

-- Smaller copies of a photo, made when it's uploaded (JSON list of widths, e.g. [160, 640, 1280]).
alter table media add column if not exists sizes text;

