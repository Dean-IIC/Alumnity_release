-- Mass emails from HQ (/hq, super administrators only): each email, and who has had it,
-- so a big send goes out in batches and never twice to the same member. Safe to run more
-- than once.

create table if not exists site.mailouts (
  id bigint generated by default as identity primary key,
  subject text not null,
  body text not null,
  -- Who it's for, as JSON: {"who":"alumni","branch":"CSE","year":2015,"skipOptedOut":true}.
  audience text not null,
  -- How many were in the audience when it was started.
  total integer not null default 0,
  created_by bigint references public.users(id) on delete set null,
  created_at bigint not null
);

create table if not exists site.mailout_sent (
  mailout_id bigint not null references site.mailouts(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  sent_at bigint not null,
  -- false: the mail server refused it (tried again with the next batch).
  ok boolean not null default true,
  primary key (mailout_id, user_id)
);

-- Only Alumnity's server reads these.
alter table site.mailouts enable row level security;
alter table site.mailout_sent enable row level security;
