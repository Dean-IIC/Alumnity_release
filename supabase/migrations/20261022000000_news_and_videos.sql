-- News and videos: the college's news, alumni stories and notices (as alpha 1 had), and the
-- college's YouTube films. Safe to run more than once; nothing is removed.

create table if not exists site.stories (
  id bigint generated by default as identity primary key,
  -- Its address: /news/<slug>. Never changes once made.
  slug text not null unique,
  -- news (something that happened), story (an alumnus's story), notice (something to do).
  kind text not null default 'news' check (kind in ('news', 'story', 'notice')),
  title text not null,
  -- One or two lines for its card.
  summary text not null default '',
  -- The full text: blank lines between paragraphs.
  body text not null default '',
  -- A picture already on the site (/assets/...), or null.
  cover_src text,
  -- A video to play with it (YouTube, Instagram...), or null.
  video_url text,
  -- Shown first, whatever its date.
  pinned boolean not null default false,
  published boolean not null default true,
  -- When it happened (newest first).
  happened_on text not null default '',
  created_at bigint not null,
  updated_at bigint not null,
  updated_by bigint references public.users(id) on delete set null
);
create index if not exists stories_published on site.stories (published, pinned desc, happened_on desc);
alter table site.stories enable row level security;

