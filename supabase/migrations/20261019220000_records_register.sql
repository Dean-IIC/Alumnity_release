-- The college's records, kept apart from the social network: the register of students
-- (everyone the college enrolled, joined Alumnity or not, added to every year) moves from
-- `public` into its own schema, `records`. Its indexes, row-level security and id counter
-- go with it. Queries name it `records.register`.
--
-- Safe to run any number of times. PGlite (local and the tests) runs every migration on
-- every start, and the first migration's `create table if not exists register` then makes
-- an empty `public.register` again; this drops that empty copy. It never drops rows: if
-- both tables exist and `public.register` has rows, it stops with an error and changes
-- nothing (move or delete those rows by hand, then run it again).

create schema if not exists records;

do $$
begin
  if to_regclass('public.register') is not null then
    if to_regclass('records.register') is null then
      alter table public.register set schema records;
    elsif exists (select 1 from public.register limit 1) then
      raise exception 'public.register and records.register both exist, and public.register has rows. Nothing was changed: move those rows into records.register (or delete them) by hand, then run this again.';
    else
      drop table public.register;
    end if;
  end if;
end $$;

-- Only if neither existed (never, after the first migration): the same table, here.
create table if not exists records.register (
  id bigint generated by default as identity primary key,
  name text not null,
  usn text not null,
  branch text not null,
  branch_name text not null,
  programme text not null,
  year integer not null
);
create index if not exists register_usn on records.register(usn);
create index if not exists register_batch on records.register(branch, year, programme);

-- Locked to the public API, as before: only Alumnity's server reads it.
alter table records.register enable row level security;
