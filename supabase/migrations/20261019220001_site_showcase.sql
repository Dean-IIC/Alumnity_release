-- The college's showcase, kept apart from the social network: what the public pages show
-- off. The gallery's albums and photos, the text of pages the college writes (the
-- director's letter, the About page's opening words) and the notices on members' Home
-- live in their own schema, `site`. The college desk (coordinators and up) changes them.
--
-- Members' own things (users, posts, messages, groups...) stay in `public`, untouched.
-- Photos added from the desk are files in the public Storage bucket `site`
-- (20261019220003_site_storage.sql); the first albums' photos are files in the repo
-- (public/assets/gallery), and their `src` says so by starting with "/assets/".
--
-- Safe to run any number of times (PGlite runs every migration on every start).

create schema if not exists site;

-- ---------- Gallery ----------

create table if not exists site.albums (
  id bigint generated by default as identity primary key,
  -- Its address: /gallery/<slug>. Never changes once made.
  slug text not null unique,
  title text not null,
  about text not null default '',
  -- When it happened, for putting albums in order, newest first: "2025-09-30", "2011-01",
  -- or '' (not known: those come last).
  happened_on text not null default '',
  -- When, in words, as precisely as we know ("September 2025", "Before 2014").
  when_text text not null default '',
  -- The photo that leads its card (null: its first photo).
  cover_photo_id bigint,
  -- Its cover at the top of the album page, and that cover as a pencil sketch for the ink
  -- bloom (null: the cover photo itself, and no separate sketch).
  cover_src text,
  cover_sketch text,
  cover_width integer,
  cover_height integer,
  -- Lower comes first; albums with the same number go newest first.
  sort integer not null default 0,
  -- Shown on the public gallery (once it has a photo).
  published boolean not null default false,
  created_at bigint not null,
  updated_at bigint not null,
  updated_by bigint references public.users(id) on delete set null
);

-- An event that happened more than once (the alumni meets, the job drives) has a part for
-- each time; a part can also hold only videos (films about the college). An album without
-- parts is one part.
create table if not exists site.album_parts (
  id bigint generated by default as identity primary key,
  album_id bigint not null references site.albums(id) on delete cascade,
  key text not null,
  -- Only albums with more than one part name them.
  title text,
  when_text text not null default '',
  -- Where its photos came from (lib/gallery.ts SOURCES), or null.
  source text,
  sort integer not null default 0,
  unique (album_id, key)
);

create table if not exists site.photos (
  id bigint generated by default as identity primary key,
  album_id bigint not null references site.albums(id) on delete cascade,
  -- Which part of the album ('' for an album without parts).
  part_key text not null default '',
  -- 1600 px at most. Either a file in the repo ("/assets/gallery/...") or a key in the
  -- Storage bucket `site` ("albums/12/....jpg").
  src text not null,
  -- 640 px wide, for the grid (same two kinds as src).
  thumb text not null,
  width integer not null,
  height integer not null,
  thumb_width integer not null,
  alt text not null,
  -- Shown on the photo, where we know what it shows.
  caption text,
  sort integer not null default 0,
  created_at bigint not null,
  unique (album_id, src)
);
create index if not exists photos_album on site.photos(album_id, sort);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'albums_cover_photo_fk') then
    alter table site.albums add constraint albums_cover_photo_fk foreign key (cover_photo_id) references site.photos(id) on delete set null;
  end if;
end $$;

-- Videos are links (YouTube, Instagram, Facebook, LinkedIn: lib/video.ts), shown after
-- their part's photos. A poster is a still for the tile, a file in the repo.
create table if not exists site.videos (
  id bigint generated by default as identity primary key,
  album_id bigint not null references site.albums(id) on delete cascade,
  part_key text not null default '',
  url text not null,
  title text not null,
  poster_src text,
  poster_width integer,
  poster_height integer,
  sort integer not null default 0,
  unique (album_id, url)
);

-- ---------- Pages the college writes ----------

-- The director's letter and other public text, by name (lib/site-pages.ts lists them and
-- keeps the words to fall back on if a row is missing). Plain text: paragraphs are
-- separated by an empty line.
create table if not exists site.pages (
  slug text primary key,
  title text not null,
  body text not null,
  -- For a letter: who signed it, and their role.
  signer_name text,
  signer_role text,
  updated_at bigint not null,
  updated_by bigint references public.users(id) on delete set null
);

-- Which one-time seeds have run (20261019220002_site_seed.sql), so a re-run never adds
-- them twice, and an album the desk deleted never comes back.
create table if not exists site.seeds (
  name text primary key,
  ran_at bigint not null
);

-- ---------- Notices (announcements) ----------

-- Moved from `public`, the same guarded way as the register (see
-- 20261019220000_records_register.sql): the empty copy a PGlite re-run makes is dropped;
-- a copy with rows stops this with an error and changes nothing.
do $$
begin
  if to_regclass('public.announcements') is not null then
    if to_regclass('site.announcements') is null then
      alter table public.announcements set schema site;
    elsif exists (select 1 from public.announcements limit 1) then
      raise exception 'public.announcements and site.announcements both exist, and public.announcements has rows. Nothing was changed: move those rows into site.announcements (or delete them) by hand, then run this again.';
    else
      drop table public.announcements;
    end if;
  end if;
end $$;

create table if not exists site.announcements (
  id bigint generated by default as identity primary key,
  author bigint references public.users(id) on delete set null,
  title text not null,
  body text not null,
  ends_at bigint,
  removed_at bigint,
  created_at bigint not null
);

-- ---------- Locked to the public API ----------

-- As every other table: row-level security on with no policies, so Supabase's public API
-- reads and writes nothing; only Alumnity's server does.
alter table site.albums enable row level security;
alter table site.album_parts enable row level security;
alter table site.photos enable row level security;
alter table site.videos enable row level security;
alter table site.pages enable row level security;
alter table site.seeds enable row level security;
alter table site.announcements enable row level security;
