-- Alumnity's schema, for Supabase Postgres (and any Postgres: the tests run it on PGlite).
--
-- Sign-in is Supabase Auth's (auth.users); `users` here is the member: who they are on the
-- college register, their role, and everything they do on Alumnity.
--
-- Security: row-level security is on for every table, with no policies, so Supabase's
-- public API (the anon and authenticated keys) can read and write nothing. Only Alumnity's
-- server, connecting with the database URL, touches this data, and its rules
-- (lib/server) decide what each member may see and do.
--
-- Times are milliseconds since 1970 (bigint), as the app has always used.

-- ---------- Members ----------

create table if not exists users (
  id bigint generated by default as identity primary key,
  -- Their Supabase Auth account (null for made-up sample members, who can't sign in).
  auth_id uuid unique,
  email text not null unique,
  name text not null,
  usn text unique,
  branch text,
  branch_name text,
  programme text,
  joined integer,
  role text not null check (role in ('student', 'alumnus', 'faculty', 'coordinator', 'admin')),
  suspended_at bigint,
  -- Signed out everywhere at this time (sessions started before it no longer count).
  signed_out_at bigint,
  -- When they were last on the site (to the hour): for the desk's numbers.
  last_seen_at bigint,
  sample integer not null default 0,
  created_at bigint not null
);
create index if not exists users_batch on users(branch, joined);
create index if not exists users_role on users(role);
create index if not exists users_created on users(created_at);

-- The college register: who studied here. Never sent to a browser; only the server's
-- register check reads it (scripts/import-register.mjs loads it; it isn't in git).
create table if not exists register (
  id bigint generated by default as identity primary key,
  name text not null,
  usn text not null,
  branch text not null,
  branch_name text not null,
  programme text not null,
  year integer not null
);
create index if not exists register_usn on register(usn);
create index if not exists register_batch on register(branch, year, programme);

-- A join or a password reset under way: the emailed code (Supabase sends it) is checked
-- against this ticket. For joining, it holds which register line they matched, so the
-- account made after the code is theirs and no one else's.
create table if not exists auth_intents (
  ticket text primary key,
  purpose text not null check (purpose in ('join', 'reset')),
  email text not null,
  found text,
  role text,
  attempts integer not null default 0,
  auth_id uuid,
  verified_at bigint,
  created_at bigint not null,
  expires_at bigint not null
);
create index if not exists auth_intents_email on auth_intents(email);

-- Recent attempts, for rate limits that hold across servers and restarts.
create table if not exists throttle (
  key text not null,
  at bigint not null
);
create index if not exists throttle_key on throttle(key, at);

-- Members' pages (lib/server/profile.ts): one JSON document each.
create table if not exists profiles (
  user_id bigint primary key references users(id) on delete cascade,
  data text not null,
  updated_at bigint not null
);

-- ---------- Connections, blocks, following ----------

create table if not exists connections (
  id bigint generated by default as identity primary key,
  requester bigint not null references users(id) on delete cascade,
  addressee bigint not null references users(id) on delete cascade,
  status text not null check (status in ('pending', 'accepted', 'declined')),
  note text not null default '',
  created_at bigint not null,
  responded_at bigint,
  unique (requester, addressee)
);
create index if not exists connections_addressee on connections(addressee, status);
create index if not exists connections_requester on connections(requester, status);

create table if not exists blocks (
  blocker bigint not null references users(id) on delete cascade,
  blocked bigint not null references users(id) on delete cascade,
  created_at bigint not null,
  primary key (blocker, blocked)
);
create index if not exists blocks_blocked on blocks(blocked);

create table if not exists follows (
  follower bigint not null references users(id) on delete cascade,
  followee bigint not null references users(id) on delete cascade,
  created_at bigint not null,
  primary key (follower, followee)
);
create index if not exists follows_followee on follows(followee);

-- ---------- Notifications and messages ----------

create table if not exists notifications (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id) on delete cascade,
  actor bigint references users(id) on delete cascade,
  kind text not null,
  text text not null,
  link text not null,
  read_at bigint,
  created_at bigint not null
);
create index if not exists notifications_user on notifications(user_id, created_at);
create index if not exists notifications_unread on notifications(user_id, read_at);

create table if not exists messages (
  id bigint generated by default as identity primary key,
  sender bigint not null references users(id) on delete cascade,
  recipient bigint not null references users(id) on delete cascade,
  body text not null,
  created_at bigint not null,
  read_at bigint
);
create index if not exists messages_pair on messages(sender, recipient, created_at);
create index if not exists messages_recipient on messages(recipient, read_at);
create index if not exists messages_sender_time on messages(sender, created_at);
create index if not exists messages_recipient_time on messages(recipient, created_at);

-- ---------- Ask a senior ----------

create table if not exists asks (
  id bigint generated by default as identity primary key,
  author bigint not null references users(id) on delete cascade,
  title text not null,
  body text not null,
  topics text not null default '[]',
  status text not null check (status in ('open', 'taken', 'answered', 'closed')),
  taker bigint references users(id) on delete set null,
  thanks text,
  created_at bigint not null,
  taken_at bigint,
  answered_at bigint
);
create index if not exists asks_author on asks(author, created_at);
create index if not exists asks_taker on asks(taker);
create index if not exists asks_status on asks(status, created_at);

create table if not exists ask_routes (
  ask_id bigint not null references asks(id) on delete cascade,
  user_id bigint not null references users(id) on delete cascade,
  reason text not null,
  primary key (ask_id, user_id)
);
create index if not exists ask_routes_user on ask_routes(user_id);

create table if not exists ask_messages (
  id bigint generated by default as identity primary key,
  ask_id bigint not null references asks(id) on delete cascade,
  author bigint not null references users(id) on delete cascade,
  body text not null,
  created_at bigint not null
);

-- ---------- Posts, media, stories ----------

create table if not exists posts (
  id bigint generated by default as identity primary key,
  author bigint not null references users(id) on delete cascade,
  body text not null,
  audience text not null check (audience in ('everyone', 'batch', 'connections')),
  removed_at bigint,
  created_at bigint not null
);
create index if not exists posts_time on posts(created_at);
create index if not exists posts_author_time on posts(author, created_at);

create table if not exists post_cheers (
  post_id bigint not null references posts(id) on delete cascade,
  user_id bigint not null references users(id) on delete cascade,
  kind text not null default 'cheer',
  primary key (post_id, user_id)
);
create index if not exists cheers_user on post_cheers(user_id);

create table if not exists post_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references posts(id) on delete cascade,
  author bigint not null references users(id) on delete cascade,
  body text not null,
  removed_at bigint,
  created_at bigint not null
);
create index if not exists comments_post on post_comments(post_id, created_at);

-- Uploads: the files are in Supabase Storage (bucket "media"), at `path`.
create table if not exists media (
  id text primary key,
  user_id bigint not null references users(id) on delete cascade,
  kind text not null,
  mime text not null,
  size bigint not null,
  path text not null,
  created_at bigint not null
);

-- An upload on its way: the browser sends the file straight to Storage (Vercel takes at most
-- 4.5 MB through a function), then the server checks it and makes it a `media` row.
create table if not exists uploads (
  id text primary key,
  user_id bigint not null references users(id) on delete cascade,
  use text not null check (use in ('photo', 'cover', 'post', 'story')),
  size bigint not null,
  created_at bigint not null
);
create index if not exists uploads_user on uploads(user_id, created_at);

create table if not exists post_media (
  post_id bigint not null references posts(id) on delete cascade,
  media_id text not null,
  position integer not null,
  primary key (post_id, position)
);
create index if not exists post_media_media on post_media(media_id);

create table if not exists stories (
  id bigint generated by default as identity primary key,
  author bigint not null references users(id) on delete cascade,
  media_id text not null,
  caption text not null default '',
  created_at bigint not null,
  expires_at bigint not null,
  removed_at bigint
);
create index if not exists stories_author on stories(author, expires_at);

create table if not exists story_views (
  story_id bigint not null references stories(id) on delete cascade,
  user_id bigint not null references users(id) on delete cascade,
  viewed_at bigint not null,
  primary key (story_id, user_id)
);

-- ---------- Events ----------

create table if not exists events (
  id bigint generated by default as identity primary key,
  organiser bigint not null references users(id) on delete cascade,
  title text not null,
  body text not null,
  starts_at bigint not null,
  ends_at bigint,
  place text not null,
  online_link text,
  capacity integer,
  cancelled_at bigint,
  created_at bigint not null
);
create index if not exists events_time on events(starts_at);

create table if not exists rsvps (
  event_id bigint not null references events(id) on delete cascade,
  user_id bigint not null references users(id) on delete cascade,
  created_at bigint not null,
  primary key (event_id, user_id)
);
create index if not exists rsvps_user on rsvps(user_id);

-- ---------- The college desk ----------

create table if not exists reports (
  id bigint generated by default as identity primary key,
  reporter bigint not null references users(id) on delete cascade,
  subject_kind text not null check (subject_kind in ('member', 'post', 'comment', 'message', 'ask')),
  subject_id bigint not null,
  reason text not null,
  status text not null default 'open' check (status in ('open', 'removed', 'dismissed')),
  resolved_by bigint references users(id) on delete set null,
  created_at bigint not null,
  resolved_at bigint
);
create index if not exists reports_status on reports(status, created_at);
create index if not exists reports_subject on reports(subject_kind, subject_id);

create table if not exists settings (
  key text primary key,
  value text not null,
  updated_by bigint references users(id) on delete set null,
  updated_at bigint not null
);

create table if not exists announcements (
  id bigint generated by default as identity primary key,
  author bigint references users(id) on delete set null,
  title text not null,
  body text not null,
  ends_at bigint,
  removed_at bigint,
  created_at bigint not null
);

create table if not exists audit (
  id bigint generated by default as identity primary key,
  actor bigint references users(id) on delete set null,
  action text not null,
  subject text not null,
  detail text,
  created_at bigint not null
);
create index if not exists audit_time on audit(created_at);

-- ---------- Locked to the public API ----------

do $$
declare t text;
begin
  foreach t in array array[
    'users', 'register', 'auth_intents', 'throttle', 'profiles', 'connections', 'blocks', 'follows',
    'notifications', 'messages', 'asks', 'ask_routes', 'ask_messages', 'posts', 'post_cheers',
    'post_comments', 'media', 'uploads', 'post_media', 'stories', 'story_views', 'events', 'rsvps', 'reports',
    'settings', 'announcements', 'audit'
  ] loop
    execute format('alter table %I enable row level security', t);
  end loop;
end $$;
