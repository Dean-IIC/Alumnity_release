-- Jobs and internships that alumni and staff put up, and students asking them for a referral.
-- Runs after 20261018000002_college_accounts.sql; safe to run again.

create table if not exists openings (
  id bigint generated by default as identity primary key,
  poster bigint not null references users(id) on delete cascade,
  kind text not null check (kind in ('job', 'internship')),
  title text not null,
  company text not null,
  place text not null default '',
  -- The branch it suits best (null: any branch).
  branch text,
  -- Where to apply, if the company has a page for it.
  link text,
  body text not null default '',
  -- Whether the poster will refer people for it (they're asked through Alumnity).
  can_refer integer not null default 1,
  closes_at bigint not null,
  closed_at bigint,
  created_at bigint not null
);
create index if not exists openings_closing on openings(closes_at);
create index if not exists openings_poster on openings(poster, created_at);

-- Someone asking the poster to refer them: one request per person per opening.
create table if not exists referral_requests (
  id bigint generated by default as identity primary key,
  opening_id bigint not null references openings(id) on delete cascade,
  requester bigint not null references users(id) on delete cascade,
  note text not null,
  created_at bigint not null,
  -- When the poster said yes (they're connected from then on, so they can talk).
  accepted_at bigint,
  unique (opening_id, requester)
);
create index if not exists referral_requests_opening on referral_requests(opening_id, created_at);

alter table reports drop constraint if exists reports_subject_kind_check;
alter table reports add constraint reports_subject_kind_check check (subject_kind in ('member', 'post', 'comment', 'message', 'ask', 'group', 'cause', 'opening'));

-- Locked to the public API, as every other table: only the server reads and writes them.
alter table openings enable row level security;
alter table referral_requests enable row level security;
